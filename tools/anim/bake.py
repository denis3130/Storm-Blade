#!/usr/bin/env python3
"""Convert the Meshy clips into the game's pose cycles and write src/n_anims.js.

usage: python3 tools/anim/bake.py CLIPDIR      (run through tools/anim/bake.sh, which fills CLIPDIR)

CLIPDIR holds <move>.json for each move of tools/anim/moves.json (clip2json.py output). The test build
game_w.html (bash mk.sh) is opened from file:// like tests/run.py; tests/lib.js and tools/anim/bake.js run in it with
window.TDATA = {skel, clips, moves}, where skel is the node list of assets/meshy/hero/hero.json (the SKEL constant of
tests/fixtures.js). bake.js leaves its result in window.TDUMP.
Exit code 1, and src/n_anims.js untouched, if a move's round trip is 2 degrees or worse (5 for the toe bend) or the file
would pass 100 KB.
"""
import asyncio, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
SB = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(SB, 'tests'))
from run import CHROME_ARGS, INIT, PAGE, chrome_path, route_assets
from playwright.async_api import async_playwright

OUT = os.path.join(SB, 'src', 'n_anims.js')
MAX_BYTES = 100 * 1024
MAX_ERR = 2.0
MAX_TOE = 5.0
HEAD = """/* ============================== baked animation cycles ==============================
   Generated by tools/anim/bake.sh from the Meshy clips in tools/anim/moves.json: do not edit by hand.
   Per move: n samples over one cycle (phase 0 = left ankle furthest forward), d = n x NP pose values
   (angles in tenths of a degree, y in mm), lift = left ankle height above its lowest point (mm),
   leg = the clip's leg length, thigh + shin (mm). err = worst bone direction error of the round trip (degrees), over the bones
   the transfer can follow (tools/anim/bake.js lists the ones it cannot). */
"""


def skeleton():
    g = json.load(open(os.path.join(SB, 'assets', 'meshy', 'hero', 'hero.json')))
    nodes = g['nodes']
    parent = {c: i for i, n in enumerate(nodes) for c in n.get('children', [])}
    joints = set(g['skins'][0]['joints'])
    return [{'i': i, 'n': n['name'], 'p': parent.get(i), 't': n.get('translation', [0, 0, 0]), 'r': n.get('rotation', [0, 0, 0, 1]),
             's': n.get('scale', [1, 1, 1]), 'bone': i in joints} for i, n in enumerate(nodes) if 'mesh' not in n]


async def bake(data):
    errors = []
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path=chrome_path(), args=CHROME_ARGS)
        pg = await (await b.new_context(viewport={'width': 640, 'height': 360}, device_scale_factor=1)).new_page()
        await pg.add_init_script(INIT)
        pg.on('pageerror', lambda e: errors.append('PAGEERROR ' + str(e)))
        pg.on('console', lambda m: m.type == 'error' and 'Failed to load resource' not in m.text and errors.append('CONSOLEERROR ' + m.text))
        await pg.route('**/*', lambda r: route_assets(r))   # one argument: the page's own files from file://
        await pg.goto('file://' + PAGE, wait_until='domcontentloaded')
        await pg.wait_for_function("window.__SB && __SB.G && __SB.G.state==='title'", timeout=60000)
        await pg.evaluate('window.requestAnimationFrame=()=>0')   # nothing else moves the rig while the clips are converted
        await pg.add_script_tag(content=open(os.path.join(SB, 'tests', 'lib.js')).read())
        await pg.add_script_tag(content='window.TDATA=' + json.dumps(data) + ';')
        await pg.add_script_tag(content=open(os.path.join(HERE, 'bake.js')).read())
        dump = await pg.evaluate('window.TDUMP===undefined?null:JSON.stringify(window.TDUMP)')
        await b.close()
    if errors or dump is None:
        sys.exit('\n'.join(errors) or 'bake.js set no window.TDUMP')
    return json.loads(dump)


def main(clipdir):
    moves = json.load(open(os.path.join(HERE, 'moves.json')))
    clips = {k: json.load(open(os.path.join(clipdir, k + '.json'))) for k in moves}
    res = asyncio.run(bake({'skel': skeleton(), 'clips': clips, 'moves': moves}))
    bad = False
    for k, r in res['report'].items():
        print('%-5s %d clip frames per cycle, phase 0 at frame %d, worst bone %s %.2f deg (%s)' % (
            k, r['frames'], r['f0'], r['worst'], r['err'], ', '.join('%s %.2f' % tuple(kv) for kv in r['bones'])))
        print('      toe bend %s' % ', '.join('%s %.2f' % tuple(kv) for kv in r['toes']))
        print('      not checked, the transfer cannot follow them: ' + ', '.join('%s %.1f' % tuple(kv) for kv in r['derived']))
        bad = bad or not r['err'] < MAX_ERR or not all(v < MAX_TOE for _, v in r['toes'])
    if bad:
        sys.exit('round trip error is %.0f degrees or more (toe bend %.0f): src/n_anims.js not written' % (MAX_ERR, MAX_TOE))
    out = HEAD + 'const ANIM=' + json.dumps(res['anim'], separators=(',', ':')) + ';\n'
    if len(out.encode()) > MAX_BYTES:
        sys.exit('src/n_anims.js would be %d bytes (limit %d)' % (len(out.encode()), MAX_BYTES))
    open(OUT, 'w').write(out)
    print('wrote src/n_anims.js (%d bytes)' % len(out.encode()))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
